// سلسلة انظر وقل - الحل الأمثل للبرمجة التنافسية
// =============================================================================

#include <bits/stdc++.h>
using namespace std;

string lookAndSay(int N) {
    string s = "1";  // العنصر الأول في السلسلة
    
    // توليد N-1 عنصر تالي
    // Generate N-1 next elements
    for (int iter = 1; iter < N; ++iter) {
        string next = "";  // السلسلة التالية
        int i = 0;
        
        // قراءة السلسلة الحالية
        // Read the current string
        while (i < s.length()) {
            char digit = s[i];  // الرقم الحالي
            int cnt = 0;         // عداد التكرار
            
            // عد عدد التكرارات المتتالية لنفس الرقم
            // Count consecutive occurrences of same digit
            while (i < s.length() && s[i] == digit) {
                cnt++;
                i++;
            }
            
            // إضافة العدد والرقم للسلسلة التالية
            // Add count and digit to next string
            next += to_string(cnt) + digit;
        }
        
        s = next;  // تحديث السلسلة
    }
    
    return s;
}

