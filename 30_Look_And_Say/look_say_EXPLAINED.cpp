// هاد الحل بيولد عناصر سلسلة "انظر وقل" (Look and Say).
// كل عنصر بيتولد من قراءة العنصر السابق وحساب تكرارات الأرقام.
// 
// الخوارزمية:
// 1. نبدأ بالعنصر الأول "1"
// 2. لتوليد العنصر التالي:
//    - نقرأ السلسلة الحالية رقم رقم
//    - نعد كم مرة متتالية ظهر كل رقم
//    - نكتب العدد ثم الرقم
// 3. نكرر N-1 مرة
// 
// مثال:
// 1. "1" -> قراءة: "one 1" -> "11"
// 2. "11" -> قراءة: "two 1s" -> "21"
// 3. "21" -> قراءة: "one 2, one 1" -> "1211"
// 4. "1211" -> قراءة: "one 1, one 2, two 1s" -> "111221"
// 5. "111221" -> قراءة: "three 1s, two 2s, one 1" -> "312211"
// 
// المميزات:
// - توليد تسلسلي للعناصر
// - حساب التكرارات المتتالية
// - تعقيد زمني: O(N * L) حيث L طول السلسلة
// - مثالي للمسابقات البرمجية

// =============================================================================
