// عد البتات - الحل الأمثل للبرمجة التنافسية
// =============================================================================

#include <bits/stdc++.h>
using namespace std;

int bitcount(int x) {
    int cnt = 0;
    // Brian Kernighan's Algorithm
    // الخوارزمية: x & (x-1) تحذف أقصى بت على اليمين
    // The trick: x & (x-1) removes the rightmost set bit
    while (x) {
        x &= (x - 1);  // حذف أقصى بت مضبوط على اليمين
        cnt++;          // زيادة العداد
    }
    return cnt;
}

