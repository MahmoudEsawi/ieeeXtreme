// هاد الحل بيستخدم خوارزمية Brian Kernighan اللي هي أسرع من فحص كل البتات
// الفكرة الذكية: العملية x & (x-1) بتحذف أقصى بت مضبوط (1) على اليمين
// 
// مثال: x = 23 = 10111 (binary)
// 1. x = 10111, x-1 = 10110, x & (x-1) = 10110, cnt = 1
// 2. x = 10110, x-1 = 10101, x & (x-1) = 10100, cnt = 2
// 3. x = 10100, x-1 = 10011, x & (x-1) = 10000, cnt = 3
// 4. x = 10000, x-1 = 01111, x & (x-1) = 00000, cnt = 4
// النتيجة: 4
// 
// المميزات:
// - تعقيد زمني: O(k) حيث k عدد البتات المضبوطة (مش O(32))
// - أسرع من فحص كل البتات
// - استخدام عمليات بتية محسنة
// - مثالي للمسابقات البرمجية

